"""The pixel art of Plot Twist: every sprite and tile, drawn as text.

Each picture is a list of rows, and each character of a row is one pixel: the
PALETTE says its color, and "." is transparent. To change a picture, change its
letters; every row of a picture must be as long as the others.

Names follow what main.py looks for:
- an item, puzzle or character by its id, or by id and status ("hold_puzzle_solved"),
  or else by kind and status ("switch_on"); the barriers as "barrier_0" and "barrier_1";
- the numbered tiles as "tile_lit", "tile_dark" and "tile_error" (main.py writes the
  number on them), on the metal "zone" of their floor puzzle;
- doors as "door_open", "door_barred", "door_locked" and "door_sealed", drawn for
  the north wall (main.py turns them for the other walls);
- the four characters as "<wizard/nurse/ghost/flash>_<down/up/right>_<0, 1 or 2>":
  0 standing, 1 and 2 walking (left is right mirrored); they all come from the same
  figure, dressed in different ways (see the end of this file);
- the room tiles as "floor_<room>" and "wall_<room>", with "_0" to "_3" for the
  pictures of a moving tile (the stormy sea around the deck); "sea_calm_0" and
  "sea_calm_1" are the calm sea of the good ending.
- decor as "decor_<picture>", shared by every piece that names it in story.py
  (as big as the piece: the crab statue is 2 x 2 tiles), and the "portal";
- the seagulls flying over the deck before the storm as "seagull_0" to "seagull_2"
  (wings up, level, down), flying left (flipped, they fly right);
A picture missing here is drawn as a colored rectangle by main.py.
"""

